/**
 * Configuration for grouping data during Excel export.
 * Enables hierarchical data representation in exported sheets.
 *
 * @private
 */
export interface ExcelGroupingSettings {
    /**
     * Array of column field names to group by.
     * Grouping is applied in order of precedence (first column = top-level groups).
     *
     * @type {string[]}
     * @example ['department', 'status'] groups first by department, then by status
     */
    groupByColumns: string[];

    /**
     * Enable/disable grouping.
     * When false, grouping configuration is ignored.
     *
     * @type {boolean}
     * @default true
     */
    enabled?: boolean;

    /**
     * Group header background color in hex format.
     * Applied to all group header rows regardless of level.
     *
     * @type {string}
     * @default '#E8E8E8'
     */
    headerBackgroundColor?: string;

    /**
     * Make group header text bold.
     * Enhances visual distinction of group headers.
     *
     * @type {boolean}
     * @default true
     */
    boldHeaders?: boolean;
}
