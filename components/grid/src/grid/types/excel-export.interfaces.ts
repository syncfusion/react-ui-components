/**
 * Excel image metadata for cell export.
 */
export interface ExcelImage {
    /**
     * Base64-encoded image data (e.g., 'data:image/png;base64,...').
     * Either `image` or `base64` may be supplied by the callback.
     *
     * @type {string}
     */
    image?: string;
    /**
     * Base64-encoded image data (e.g., 'data:image/png;base64,...').
     * When provided, this is preferred and will be stripped before workbook insertion.
     *
     * @type {string}
     */
    base64?: string;
    /**
     * The row index of the top-left cell in the merged range.
     *
     * @type {number}
     */
    row?: number;
    /**
     * The column index of the top-left cell in the merged range.
     *
     * @type {number}
     */
    column?: number;
    /**
     * The row index of the last cell in the merged range
     *
     * @type {number}
     */
    lastRow?: number;
    /**
     * The column index of the last cell in the merged range
     *
     * @type {number}
     */
    lastColumn?: number;

    /**
     * External URL to image resource
     *
     * @type {string}
     */
    url?: string;

    /**
     * Image height in pixels
     *
     * @type {number}
     */
    height: number;

    /**
     * Image width in pixels
     *
     * @type {number}
     */
    width: number;

    /**
     * Alternative text for accessibility
     *
     * @type {string}
     */
    altText?: string;
}

